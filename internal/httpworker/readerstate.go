// Автомат режимов читателя воркеров (T-262, ТЗ tasks/TZ-fsm.md §3 ФТ-8):
// единая точка правды о дискретном режиме горутины чтения q:http цикла
// Run. До T-262 режим был размазан по порядку if читателя
// (failed/infraDown/failStreak/infraStreak — часть шести переменных,
// кодировавших пять режимов, аудит §2 № 8): теперь режим — значение
// readerMode, выбираемое единственной функцией readerDecide по
// наблюдениям прохода; порядок приоритетов пауз фиксирует таблица
// ниже, а не порядок if. Полная таблица режимов (включая паузу-браузер
// и паузу-темп) — internal/renderworker/readerstate.go: автомат один
// и тот же в обоих воркерах (ФТ-8), здесь — его q:http-проекция.
//
// # Датчики q:http
//
// В HTTP-этапе смонтированы два датчика из четырёх:
//
//	инфраструктура  устойчивый InfraError публикации результата
//	                (OOM/соединение Redis, T-152): флаг ставит
//	                диспетчер (queue.IsInfra), гасит проба записи
//	                (Reliab.Writable) или успех обработки
//	предохранитель  доставки падают подряд (failed ≥ Consume —
//	                систематический сбой обработки, T-139)
//
// Браузера (Options.Alive — зонд renderworker) и потолка темпа
// (Options.Rate, T-240 — батч-режим воркера B) в q:http нет: режимы Б
// и Т входят в enum для паритета автомата (ФТ-8: один enum в каждом
// воркере) и структурно недостижимы — browser=false и rate=false
// читаются нулевыми, readerDecide их не выбирает (юнит-тест
// фиксирует недостижимость).
//
// # Переходы: наблюдения прохода → режим (приоритет сверху вниз)
//
// Номера строк — полной таблицы renderworker/readerstate.go (П1
// пауза-браузер и П4 пауза-темп в q:http не проектируются: датчиков
// нет); «—» — значение не наблюдается (датчик не смонтирован) и
// решением не читается.
//
//	| № | Инфра (infra × writable) | failed | Режим | Действия прохода |
//	|---|--------------------------|--------|-------|------------------|
//	| П2 | флаг горит, проба падает (writable=false) | — | И | Warn, wait workerFailBackoff(infraStreak), повторное наблюдение |
//	| П3 | флага нет или проба прошла | > 0 и ≥ batch | Ф | Warn, wait workerFailBackoff(failStreak), затем чтение |
//	| П5 | флага нет или проба прошла | < batch | Ч | XREADGROUP |
//
// Семантика против исходного читателя не меняется: инфра-пауза не
// читает стрим (попытки не горят), предохранитель читает после паузы
// (душит темп, не блокирует чтение до нулевого счётчика).
//
// # Паритет паник (ФТ-8, фикс T-262)
//
// Горутина доставки http-worker получает recover-учёт по образцу
// renderworker (worker.go, инвариант И3 его автомата): паника
// обработки (загрузка/Options.OnResult) — та же неподтверждённая
// доставка: failed.Add(1), Error-лог со стеком, доставка без XACK
// вернётся повторной доставкой (XAUTOCLAIM, T-025); in-flight соседей
// и graceful shutdown сохраняются — паника доставки перестала убивать
// юнит (до T-262 recover в q:http не было). Серия паник душится
// предохранителем (П3) как серия ошибок — попытки доставок не
// пережигаются на полном ходу.
//
// Покрытие — горутина доставки (диспетчер XREADGROUP): клейм-путь
// RecoverLoop (тот же processDelivery от имени восстановителя)
// recover'ом не покрыт — ровно как в renderworker-образце (паритет
// ФТ-8); детерминированная паника задачи на клейме (через
// claim_min_idle) по-прежнему роняет юнит — расширение покрытия
// за рамки паритета меняло бы непомеченное ТЗ поведение (ТЗ-fsm §4)
// и оставлено кандидатом в отдельную задачу.

package httpworker

import "fmt"

// readerMode — дискретный режим читателя (ФТ-8): значение автомата,
// выбираемое readerDecide по наблюдениям прохода. Набор режимов общий
// с renderworker (браузер/темп); порядок констант — приоритет пауз
// полной таблицы (internal/renderworker/readerstate.go).
type readerMode int8

const (
	modeConsume      readerMode = iota // Ч: пачка доставок читается
	modePauseBrowser                   // Б: датчик браузера — только renderworker, здесь недостижим
	modePauseInfra                     // И: InfraError публикации, стрим не читается
	modePauseFail                      // Ф: предохранитель, после паузы читает
	modePauseRate                      // Т: потолок темпа — только renderworker, здесь недостижим
)

// String — имя режима (термины полной таблицы переходов) для
// сообщений тестов.
func (m readerMode) String() string {
	switch m {
	case modeConsume:
		return "чтение"
	case modePauseBrowser:
		return "пауза-браузер"
	case modePauseInfra:
		return "пауза-инфра"
	case modePauseFail:
		return "пауза-предохранитель"
	case modePauseRate:
		return "пауза-темп"
	}
	return fmt.Sprintf("readerMode(%d)", int8(m))
}

// readerObs — наблюдения одного прохода читателя (ФТ-8): вход
// readerDecide. Поля идут парами «датчик × значение»: несмонтированный
// датчик (browser — зонд браузера renderworker, rate — потолок темпа
// T-240) не опрашивается, его значение решением не читается; writable
// наблюдается только при горящем флаге infra (проба записи — один SET,
// T-152: здоровый цикл Redis не дёргает).
type readerObs struct {
	browser   bool  // смонтирован зонд браузера (q:http — всегда false)
	alive     bool  // браузер жив (наблюдается при browser)
	infra     bool  // горит флаг устойчивого инфра-сбоя публикации (T-152)
	writable  bool  // проба записи Redis прошла (наблюдается при infra)
	failed    int64 // доставок подряд без подтверждения (счётчик диспетчера)
	batch     int   // пачка чтения (Options.Consume) — порог предохранителя
	rate      bool  // смонтирован потолок темпа (q:http — всегда false)
	allowance int   // свободные слоты окна темпа (наблюдается при rate)
}

// readerDecide — единственная функция переходов автомата режимов
// (ФТ-8): наблюдения прохода → режим, приоритет полной таблицы
// переходов (internal/renderworker/readerstate.go; в q:http — её
// строки П2/П3/П5), а не порядок if цикла. Без памяти: серии пауз
// (длительности) и счётчик failed живут в цикле. Условие
// предохранителя требует failed > 0: нулевой счётчик — не пауза при
// любом batch (ветка сброса серии исходного читателя).
func readerDecide(o readerObs) readerMode {
	switch {
	case o.browser && !o.alive:
		return modePauseBrowser
	case o.infra && !o.writable:
		return modePauseInfra
	case o.failed > 0 && o.batch > 0 && o.failed >= int64(o.batch):
		return modePauseFail
	case o.rate && o.allowance <= 0:
		return modePauseRate
	}
	return modeConsume
}
