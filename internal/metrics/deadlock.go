// Счётчик повторов операторов БД после дедлока 40P01 (T-268): обёртка
// db.RetryDeadlock гасит остаточные и будущие циклы блокировок счётчиков
// (структурный инвариант T-267/T-267-фиксы убирает известные, но не
// доказывает отсутствия новых) в горячих точках конвейера — транзакция
// записи результата http-worker, транзакция решения ретрая scheduler,
// autocommit-операторы записи DNS-эпизода. Счётчик монотонный: каждое
// событие — один фактический повтор (жертва дедлока уже прождала
// deadlock_timeout, повтор почти всегда успевает). Единичные события —
// норма (страховка работает, задача не уходит в ределивери полным
// эпизодом); устойчивый рост — новый цикл блокировок: разбор —
// runbooks.md §2.8, ретрай страховка, а не лечение.
//
// Архитектурно — та же точка регистрации, что у приборов этапов
// (T-077): каждый сервис создаёт счётчик в СВОЁМ реестре
// (NewDBDeadlockRetried), метка service подставляется фабрикой —
// разбивка по сервисам бесплатно; имя и HELP едины для всех трёх
// сервисов (http-worker, dns-worker, scheduler) — регистрация в одном
// реестре (комбинированные сборки) конфликтом описаний не падает.
package metrics

import (
	"github.com/prometheus/client_golang/prometheus"
)

// NewDBDeadlockRetried — счётчик crawler_db_deadlock_retried_total в
// реестре reg (метка service подставляется фабрикой); nil reg — nil
// (вызывающие хранят его в nil-безопасной обёртке своих приборов).
// Идемпотентен (T-076): повторный вызов делит уже созданный вектор.
func NewDBDeadlockRetried(reg *Registry) prometheus.Counter {
	if reg == nil {
		return nil
	}
	return reg.MustCounter(prometheus.CounterOpts{
		Name: "crawler_db_deadlock_retried_total",
		Help: "Повторы операторов БД после дедлока 40P01 (db.RetryDeadlock, T-268): страховка поверх инварианта порядка блокировок счётчиков (T-267) — повтор идемпотентной транзакции/команды в горячих точках конвейера (запись результата http-worker, решение ретрая scheduler, операторы записи DNS-эпизода), задача не уходит в ределивери полным эпизодом. Единичные события — норма (страховка работает); устойчивый рост — новый цикл блокировок, разбор runbooks.md §2.8.",
	}).WithLabelValues()
}
