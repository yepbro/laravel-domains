// Автомат доставки записи стрима (T-260, ТЗ tasks/TZ-fsm.md §3 ФТ-6):
// единая точка правды о состояниях и переходах одной записи рабочего
// стрима (q:dns/q:http/q:render/q:render-fallback/q:analyze) внутри
// группы потребителей. Состояние закодировано принадлежностью записи
// носителям: телу стрима (сама запись), PEL группы (доставки без
// подтверждения; счётчик доставок RetryCount живёт только там) и q:dead
// (карантин). Формализация не переписывает переходы на FSM-фреймворк
// (ТЗ-fsm §1): они остаются командами Redis с присущей им атомарностью;
// эта таблица — то, с чем сверяются все писатели (перечислены ниже).
// Писатели живут в этом же пакете (Consume, Processing, Claim/bury,
// Refund/RefundUnclassified, RecoverLoop, TrimLoop) — внешних писателей
// нет: воркеры и восстановители пользуются этими входами. Смежный
// автомат рендер-состояния строки — internal/renderworker/worker.go
// (T-259); состояние домена — internal/scheduler/checkstate.go (T-255).
//
// # Состояния
//
//	Д0 «новая»        запись в стриме, группой не читалась: доставок
//	                   нет, счётчика не существует
//	Д1 «в работе(n)»  запись в PEL группы за потребителем, n ≥ 1 —
//	                   счётчик доставок (первое чтение = 1, каждый
//	                   клейм +1); XACK отложен до результата в БД
//	                   (ТЗ 4.2) — запись чьей-то работы в полёте либо
//	                   зависшая (воркер пал/отменён)
//	Д2 «карантин»     терминальное: попытки исчерпаны (n > max_attempts),
//	                   Dead опубликован в q:dead, исходная запись
//	                   подтверждена (XACK) — в PEL её больше нет;
//	                   разбор ручной (q:dead потребителя не имеет).
//	                   Д2и «неидентифицируемая» — под-состояние записи
//	                   без task_id: синтетический идентификатор
//	                   unknown:<stream>:<entry-id>, предметных полей
//	                   нет (ФТ-6.1)
//	Д3 «подтверждена» терминальное: обработка безошибочна, результат
//	                   в БД, XACK — в PEL записи нет; тело остаётся
//	                   в стриме до обрезки (MAXLEN/XTRIM, trim.go)
//	Д4 «усечена»      терминальное: запись срезана политикой MAXLEN —
//	                   для очереди её больше нет; неподтверждённая
//	                   (Д1) теряется для доставок, восстановление —
//	                   источник истины PostgreSQL (ТЗ 3.4: lease/
//	                   перепроверка), XAUTOCLAIM вычищает её из PEL
//
// # Переходы: состояние × событие × охраны × цель × побочные действия
//
//	| № | Исходное | Событие | Охраны | Цель | Побочные действия | Писатель |
//	|---|----------|---------|--------|------|-------------------|----------|
//	| П1 | Д0 | первое чтение группы (XREADGROUP ">") | — | Д1(1) | счётчик 1 (ставит Redis) | redisq.go Consume |
//	| П2 | Д1(n) | безошибочная обработка (результат записан в БД) | — | Д3 | XACK; тело в стриме до обрезки | reliab.go Processing/ProcessingAttempt |
//	| П3 | Д1(n) | ошибка обработки | — | Д1(n) | без XACK: запись вернётся клеймом; счётчик не меняется | Processing/ProcessingAttempt |
//	| П4 | Д1(n) | клейм по простою (XAUTOCLAIM, MinIdle), классификация успешна | n+1 ≤ max_attempts | Д1(n+1) | счётчик +1, idle 0, закрепление за потребителем восстановителя; возврат в работу обработчиком | reliab.go Claim + recover.go RecoverLoop |
//	| П5 | Д1(n) | клейм, классификация успешна | n+1 > max_attempts, task_id есть | Д2 | Dead с task_id и предметными полями (T-105), публикация ДО XACK (сбой XACK — дубль в q:dead, не потеря); XACK; хук OnBury (crawler_queue_dead_buried_total, T-154) | reliab.go bury |
//	| П6 | Д1(n) | клейм, классификация успешна | n+1 > max_attempts, task_id нет (тело вне форматов пакета) | Д2и | Dead с синтетическим unknown:<stream>:<entry-id> без предметных полей; XACK; хук OnBuryUnidentified (crawler_queue_dead_unidentified_total) — до T-260 вечный цикл клейма, теперь терминальное состояние (ФТ-6.1) | reliab.go bury |
//	| П7 | Д1(n+1) (после клейма П4) | классификация сбойна (ошибка XPENDING), обработка не начиналась | — | Д1(n) | запись отдаётся вторым результатом Claim (unclassified); возврат попытки XCLAIM JUSTID RETRYCOUNT n (RefundUnclassified, счётчик читается в момент возврата) — попытка не сгорает (ФТ-6.2); XCLAIM сбрасывает idle — запись снова зреет claim_min_idle (плата за честный счётчик); возврат не состоялся — остаётся Д1(n+1), следующим клеймом | reliab.go Claim/RefundUnclassified + recover.go |
//	| П8 | Д1(n+1) (после клейма П4) | отмена RecoverLoop посреди пачки, обработка записи не начиналась | время от клейма < claim_min_idle (инвариант T-153) | Д1(n) | возврат попытки XCLAIM JUSTID RETRYCOUNT n (Refund, T-222); сброс idle — как П7; начатая обработкой запись попытку расходует | recover.go RecoverLoopAttempt |
//	| П9 | Д1(n) | усечение записи при живом PEL (XADD MAXLEN ~ публикации / ручной XTRIM; TrimLoop неподтверждённые не режет) | — | Д4 | XAUTOCLAIM вычищает из PEL (значения пусты), восстановления доставками нет | redisq.go Publish + reliab.go Claim |
//	| П10 | Д1(n) | запись покинула PEL между командами (подтверждена, похоронена или усечена кем-то другим) | — | вне PEL (Д2/Д3/Д4) | наблюдение классификации: пропуск без действий | reliab.go Claim/RefundUnclassified |
//
// # Инварианты
//
//	И1  Счётчик доставок живёт только в PEL записи (RetryCount): тело
//	    записи immutable, отдельных ключей-счётчиков нет — счётчик
//	    переживает рестарты воркеров и согласован при многих
//	    восстановителях.
//	И2  XACK только после безошибочной обработки (результат в БД, П2)
//	    либо после публикации Dead (П5/П6) — доставка at-least-once,
//	    повторная обработка идемпотентна (ТЗ 3.4); сбой XACK оставляет
//	    запись в PEL — повторный проход безопасен.
//	И3  Dead публикуется до XACK исходной записи: сбой XACK даёт дубль
//	    в q:dead на следующем проходе — карантин без потребителя,
//	    дубль предпочтительнее потери.
//	И4  Попытка расходуется только доставкой (чтение П1, клейм П4–П7);
//	    путь, где обработка не начиналась, попытку возвращает
//	    (RETRYCOUNT n): отмена хвоста пачки (П8, T-222) и незавершённая
//	    классификация (П7, ФТ-6.2) — окно возврата T-222 расширено
//	    с «отмена ctx» на «любая незавершённая классификация».
//	И5  Возврат гасит ровно свой инкремент: инвариант T-153 (обход пачки
//	    < claim_min_idle) — вне его запись мог переклеймить соседний
//	    воркер, и возврат погасил бы чужой инкремент (возврат
//	    пропускается, Warn).
//	И6  Запись без task_id не имеет циклического пути в bury: ветка П6 —
//	    единственный способ её захоронения, и она терминальна (до T-260 —
//	    вечный цикл клейма). Из PEL такая запись выходит и штатными
//	    путями — успешной обработкой (П2; валидаторы сообщений task_id
//	    не проверяют, тело может распознаться форматом стрима),
//	    усечением (П9), внешним подтверждением (П10). Синтетический
//	    идентификатор — только для неидентифицируемых записей: живые
//	    задачи (task_id есть) несут свой идентификатор и предметные
//	    поля (П5) — предмет идентифицируемых задач в q:dead
//	    не теряется.
//
// Не-переходы (состояние доставки не меняют): гейт записи T-152
// (Writable — клейм пропускается, попытки не расходуются); повторное
// чтение потребителем своего PEL не выполняется (Consume читает только
// ">"); монитор читает глубины (XLEN/PEL) без команд группы.

