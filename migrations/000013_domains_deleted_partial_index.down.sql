-- T-170: откат частичного индекса deleted-доменов.
--
-- DROP INDEX на партиционированном родителе каскадно удаляет дочерние
-- индексы всех партиций; данные не затрагиваются. Очистка ingest
-- продолжит работать seq-сканом (план «от результатов», как до
-- миграции) — корректность от индекса не зависит.

