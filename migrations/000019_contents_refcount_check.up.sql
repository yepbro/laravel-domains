-- T-265 (ТЗ-fsm §3 ФТ-11): неотрицательность счётчика ссылок контента —
-- CHECK contents.refcount >= 0.
--
-- Инвариант всегда держали SQL-охраны писателей (спецификация автомата
-- refcount — doc-комментарий internal/content/pack.go, инвариант И1):
-- точечные операторы снимают ссылку только с живой строки (охранный
-- предикат refcount > 0: UPDATE 0 → ErrNotFound у Delete, ErrRefIntegrity
-- у свопа T-044), массовые проходы (retention T-166, очистка
-- deleted-доменов T-020) клэмпят GREATEST(refcount − n, 0) — код
-- отрицательного refcount не порождает вовсе. CHECK переводит инвариант
-- из процедурного в схемный: ручной SQL, будущие писатели и эксперименты
-- не смогут зафиксировать отрицательный счётчик. Отрицательный refcount
-- ломал бы семантику «0 = мёртвый» (Get и дедупликация фильтруют
-- refcount > 0 — «−1» выглядел бы мёртвым) и навсегда маскировал бы
-- двойное списание ссылки: рассинхрон перестал бы быть наблюдаемым.
--
-- NOT VALID — по регламенту миграций (ТЗ-fsm §4): contents — миллионы
-- строк и постоянный приток (рост контента ≈20 GiB/сут при ≈16 KiB/блок,
-- docs/load-measurements.md §7/§12), сканировать таблицу на деплое
-- запрещено; ограничение в режиме NOT VALID проверяет ТОЛЬКО новые и
-- изменяемые строки (существующие данные не трогает — нарушителей среди
-- них нет, инвариант держали охраны).
-- VALIDATE CONSTRAINT — отдельным шагом по регламенту после выдержки
-- (docs/schema.md «CHECK-инварианты»); contents не секционирована
-- (миграция 000001) — ограничение одно, валидация одним оператором.
--
-- HOT: refcount не входит ни в один индекс (PK по hash,
-- contents_pack_off_idx по (pack_id, off), миграция 000007 — точечные
-- апдейты счётчика остаются HOT) — индексных записей не добавляет,
-- картину HOT-апдейтов не меняет (docs/schema.md «HOT-апдейты»).

ALTER TABLE contents
    ADD CONSTRAINT contents_refcount_check
    CHECK (refcount >= 0) NOT VALID;

COMMENT ON CONSTRAINT contents_refcount_check ON contents IS
    'Неотрицательность счётчика ссылок контента (T-265): refcount >= 0, инвариант «0 = мёртвый»; добавлено NOT VALID, VALIDATE — по регламенту docs/schema.md';
